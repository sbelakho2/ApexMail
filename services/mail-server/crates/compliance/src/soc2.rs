//! SOC 2 Type II compliance subsystem.
//!
//! Provides:
//!   * The Trust Service Criteria (TSC) control catalog (Common Criteria CC1–CC9
//!     plus Availability A1, Confidentiality C1, Processing Integrity PI1, and
//!     Privacy P1–P8 categories).
//!   * Automated evidence collectors that pull point-in-time evidence from the
//!     audit log, secrets table, risk-scoring data, and other compliance
//!     artifacts.  Each piece of evidence is hash-locked (SHA-256) and stored
//!     in `soc2_control_evidence` with the canonical period it covers.
//!   * A run-tracker (`soc2_evidence_collection_runs`) for the cron worker so
//!     ops can see which controls passed automated evidence collection.
//!   * A stale-attestation sweep (`stale_evidence_controls` for the pure
//!     query, `sweep_stale_attestations` for the persisting entry point)
//!     that flags every in-scope control whose `next_attestation_at` has
//!     passed or whose required evidence set is incomplete/stale.
//!
//! Database schema lives in migration `039_soc2_hipaa_trust_portal.sql`.
//!
//! The catalog seeded here mirrors AICPA TSP Section 100 (2017, with the 2022
//! Points of Focus refresh).  A SOC 2 report is generated by exporting the
//! controls list together with evidence for the audit period.

