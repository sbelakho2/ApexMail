//! SOC 2 Type II compliance subsystem.
//!
//! Provides:
//!   * The Trust Service Criteria (TSC) control catalog (Common Criteria CC1–CC9
//!     plus Availability A1, Confidentiality C1, Processing Integrity PI1, and
//!     Privacy P1–P8 categories).
//!   * Automated evidence collectors that pull point-in-time evidence from the
//!     audit log, secrets table, risk-scoring data, and other compliance
//!     artifacts.  Each piece of evidence is hash-locked (SHA-256) and stored
//!     in `soc2_control_evidence` with the canonical period it covers.
//!   * A run-tracker (`soc2_evidence_collection_runs`) for the cron worker so
//!     ops can see which controls passed automated evidence collection.
//!
//! Database schema lives in migration `039_soc2_hipaa_trust_portal.sql`.
//!
//! The catalog seeded here mirrors AICPA TSP Section 100 (2017, with the 2022
//! Points of Focus refresh).  A SOC 2 report is generated by exporting the
//! controls list together with evidence for the audit period.

use chrono::{DateTime, Duration, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use sqlx::PgPool;
use std::time::Instant;
use tracing::{info, warn};
use uuid::Uuid;

// ─── Public types ──────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ControlStatus {
    InScope,
    NotApplicable,
    Deferred,
}

impl ControlStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::InScope => "in_scope",
            Self::NotApplicable => "not_applicable",
            Self::Deferred => "deferred",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AutomationLevel {
    Manual,
    Automated,
    Hybrid,
}

impl AutomationLevel {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Manual => "manual",
            Self::Automated => "automated",
            Self::Hybrid => "hybrid",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Control {
    pub id: String,
    pub control_id: String,
    pub category: String,
    pub title: String,
    pub description: String,
    pub owner: String,
    pub status: String,
    pub evidence_required: serde_json::Value,
    pub automation: String,
    pub last_attested_at: Option<DateTime<Utc>>,
    pub next_attestation_at: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ControlEvidence {
    pub id: String,
    pub control_id: String,
    pub evidence_type: String,
    pub source: String,
    pub payload: serde_json::Value,
    pub sha256_hash: String,
    pub storage_url: Option<String>,
    pub period_start: DateTime<Utc>,
    pub period_end: DateTime<Utc>,
    pub collected_at: DateTime<Utc>,
    pub collected_by: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CollectionRunSummary {
    pub started_at: DateTime<Utc>,
    pub finished_at: DateTime<Utc>,
    pub controls_attempted: u32,
    pub controls_succeeded: u32,
    pub controls_failed: u32,
    pub items_collected: u32,
    pub failures: Vec<String>,
}

