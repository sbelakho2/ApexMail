// ─── Service ───────────────────────────────────────────────────────────────

/// SOC2 service.  Constructed once at startup; cheap to clone.
#[derive(Clone)]
pub struct Soc2Service {
    db: PgPool,
    /// How frequently each control should be re-attested.  Used to compute
    /// `next_attestation_at` when seeding/updating controls.
    attestation_period_days: i64,
}

impl Soc2Service {
    /// Construct.  Pass the DB pool; the attestation period defaults to 90 days
    /// (matching common SOC 2 Type II audit cadences).
    pub fn new(db: PgPool) -> Self {
        Self {
            db,
            attestation_period_days: 90,
        }
    }

    pub fn with_attestation_period(mut self, days: i64) -> Self {
        self.attestation_period_days = days;
        self
    }

    /// Idempotently seed the default control catalog.  Existing controls are
    /// updated in-place if their description/owner has changed but their
    /// `last_attested_at` is preserved.
    pub async fn seed_default_controls(&self) -> Result<usize, String> {
        let mut inserted = 0usize;
        let now = Utc::now();
        for seed in DEFAULT_CONTROLS {
            let evidence_json = serde_json::to_value(seed.evidence_required)
                .map_err(|e| format!("evidence JSON: {e}"))?;
            let id = format!(
                "control-{}",
                seed.control_id.to_lowercase().replace('.', "-")
            );
            let res = sqlx::query(
                "INSERT INTO soc2_controls
                   (id, control_id, category, title, description, owner, status,
                    evidence_required, automation, last_attested_at,
                    next_attestation_at, created_at, updated_at)
                 VALUES ($1,$2,$3,$4,$5,$6,'in_scope',$7,$8,NULL,$9,$10,$10)
                 ON CONFLICT (control_id) DO UPDATE SET
                   category = EXCLUDED.category,
                   title = EXCLUDED.title,
                   description = EXCLUDED.description,
                   owner = EXCLUDED.owner,
                   evidence_required = EXCLUDED.evidence_required,
                   automation = EXCLUDED.automation,
                   updated_at = EXCLUDED.updated_at",
            )
            .bind(&id)
            .bind(seed.control_id)
            .bind(seed.category)
            .bind(seed.title)
            .bind(seed.description)
            .bind(seed.owner)
            .bind(&evidence_json)
            .bind(seed.automation.as_str())
            .bind(now + Duration::days(self.attestation_period_days))
            .bind(now)
            .execute(&self.db)
            .await
            .map_err(|e| format!("DB error: {e}"))?;
            inserted += res.rows_affected() as usize;
        }
        info!(controls = inserted, "Seeded SOC2 controls");
        Ok(inserted)
    }

    pub async fn list_controls(&self) -> Result<Vec<Control>, String> {
        let rows: Vec<Control> = sqlx::query_as::<_, ControlRow>(
            "SELECT id, control_id, category, title, description, owner, status,
                    evidence_required, automation, last_attested_at,
                    next_attestation_at, created_at, updated_at
             FROM soc2_controls ORDER BY control_id",
        )
        .fetch_all(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?
        .into_iter()
        .map(Into::into)
        .collect();
        Ok(rows)
    }

    pub async fn get_control(&self, control_id: &str) -> Result<Option<Control>, String> {
        let row: Option<ControlRow> = sqlx::query_as(
            "SELECT id, control_id, category, title, description, owner, status,
                    evidence_required, automation, last_attested_at,
                    next_attestation_at, created_at, updated_at
             FROM soc2_controls WHERE control_id = $1",
        )
        .bind(control_id)
        .fetch_optional(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;
        Ok(row.map(Into::into))
    }

    pub async fn set_status(&self, control_id: &str, status: ControlStatus) -> Result<(), String> {
        sqlx::query(
            "UPDATE soc2_controls SET status = $1, updated_at = NOW() WHERE control_id = $2",
        )
        .bind(status.as_str())
        .bind(control_id)
        .execute(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;
        Ok(())
    }

    /// Record an evidence item.  Caller computes the canonical payload; the
    /// SHA-256 is computed here from the JSON-serialised payload.
    pub async fn record_evidence(
        &self,
        control_id: &str,
        evidence_type: &str,
        source: &str,
        payload: serde_json::Value,
        period_start: DateTime<Utc>,
        period_end: DateTime<Utc>,
        collected_by: &str,
    ) -> Result<ControlEvidence, String> {
        let id = Uuid::new_v4().to_string();
        let canonical = serde_json::to_string(&payload).map_err(|e| format!("JSON: {e}"))?;
        let mut hasher = Sha256::new();
        hasher.update(canonical.as_bytes());
        let sha256_hash = hex::encode(hasher.finalize());
        let collected_at = Utc::now();

        sqlx::query(
            "INSERT INTO soc2_control_evidence
               (id, control_id, evidence_type, source, payload, sha256_hash,
                storage_url, period_start, period_end, collected_at, collected_by)
             VALUES ($1,$2,$3,$4,$5,$6,NULL,$7,$8,$9,$10)
             ON CONFLICT (control_id, evidence_type, period_start, period_end)
             DO UPDATE SET
               payload = EXCLUDED.payload,
               sha256_hash = EXCLUDED.sha256_hash,
               collected_at = EXCLUDED.collected_at,
               collected_by = EXCLUDED.collected_by",
        )
        .bind(&id)
        .bind(control_id)
        .bind(evidence_type)
        .bind(source)
        .bind(&payload)
        .bind(&sha256_hash)
        .bind(period_start)
        .bind(period_end)
        .bind(collected_at)
        .bind(collected_by)
        .execute(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;

        // Mark the control as attested and schedule the next attestation.
        sqlx::query(
            "UPDATE soc2_controls
             SET last_attested_at = $1,
                 next_attestation_at = $2,
                 updated_at = $1
             WHERE control_id = $3",
        )
        .bind(collected_at)
        .bind(collected_at + Duration::days(self.attestation_period_days))
        .bind(control_id)
        .execute(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;

        Ok(ControlEvidence {
            id,
            control_id: control_id.to_string(),
            evidence_type: evidence_type.to_string(),
            source: source.to_string(),
            payload,
            sha256_hash,
            storage_url: None,
            period_start,
            period_end,
            collected_at,
            collected_by: collected_by.to_string(),
        })
    }

    pub async fn list_evidence_for_control(
        &self,
        control_id: &str,
        limit: i64,
    ) -> Result<Vec<ControlEvidence>, String> {
        let rows: Vec<EvidenceRow> = sqlx::query_as(
            "SELECT id, control_id, evidence_type, source, payload, sha256_hash,
                    storage_url, period_start, period_end, collected_at, collected_by
             FROM soc2_control_evidence
             WHERE control_id = $1
             ORDER BY collected_at DESC
             LIMIT $2",
        )
        .bind(control_id)
        .bind(limit)
        .fetch_all(&self.db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;
        Ok(rows.into_iter().map(Into::into).collect())
    }

    /// Run all configured automated collectors over the supplied period.
    /// Logs a row in `soc2_evidence_collection_runs` for each control attempted.
    pub async fn run_automated_collectors(
        &self,
        period_start: DateTime<Utc>,
        period_end: DateTime<Utc>,
    ) -> Result<CollectionRunSummary, String> {
        let started_at = Utc::now();
        let mut summary = CollectionRunSummary {
            started_at,
            finished_at: started_at,
            controls_attempted: 0,
            controls_succeeded: 0,
            controls_failed: 0,
            items_collected: 0,
            failures: Vec::new(),
        };

        let collectors: Vec<Box<dyn EvidenceCollector + Send + Sync>> = vec![
            Box::new(AuditLogEvidenceCollector),
            Box::new(SecretRotationEvidenceCollector),
            Box::new(RiskProfileEvidenceCollector),
            Box::new(ScanResultsEvidenceCollector),
            Box::new(ConsentRecordsEvidenceCollector),
            Box::new(GdprDeletionEvidenceCollector),
        ];

        for collector in collectors {
            summary.controls_attempted += 1;
            let started = Instant::now();
            match collector.collect(&self.db, period_start, period_end).await {
                Ok(item) => {
                    let _ = self
                        .record_evidence(
                            collector.control_id(),
                            collector.evidence_type(),
                            collector.source(),
                            item.payload,
                            period_start,
                            period_end,
                            "automated_collector",
                        )
                        .await
                        .map_err(|e| {
                            warn!(error = %e, control = collector.control_id(), "evidence persist failed");
                            e
                        });
                    summary.controls_succeeded += 1;
                    summary.items_collected += item.items as u32;
                    let _ = sqlx::query(
                        "INSERT INTO soc2_evidence_collection_runs
                           (control_id, evidence_type, run_at, status,
                            items_collected, duration_ms, error)
                         VALUES ($1,$2,$3,'success',$4,$5,NULL)",
                    )
                    .bind(collector.control_id())
                    .bind(collector.evidence_type())
                    .bind(Utc::now())
                    .bind(item.items as i32)
                    .bind(started.elapsed().as_millis() as i32)
                    .execute(&self.db)
                    .await;
                }
                Err(e) => {
                    summary.controls_failed += 1;
                    summary
                        .failures
                        .push(format!("{}: {e}", collector.control_id()));
                    let _ = sqlx::query(
                        "INSERT INTO soc2_evidence_collection_runs
                           (control_id, evidence_type, run_at, status,
                            items_collected, duration_ms, error)
                         VALUES ($1,$2,$3,'failed',0,$4,$5)",
                    )
                    .bind(collector.control_id())
                    .bind(collector.evidence_type())
                    .bind(Utc::now())
                    .bind(started.elapsed().as_millis() as i32)
                    .bind(e)
                    .execute(&self.db)
                    .await;
                }
            }
        }

        summary.finished_at = Utc::now();
        info!(
            attempted = summary.controls_attempted,
            succeeded = summary.controls_succeeded,
            failed = summary.controls_failed,
            items = summary.items_collected,
            "SOC2 evidence collection run finished"
        );
        Ok(summary)
    }
}

