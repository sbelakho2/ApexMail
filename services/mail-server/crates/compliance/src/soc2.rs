#[derive(Debug, Clone)]
pub struct CollectedItem {
    pub payload: serde_json::Value,
    pub items: u64,
}

/// Trait implemented by automated evidence sources.  Each collector is bound
/// to a single (control_id, evidence_type, source) tuple so the resulting
/// evidence row is well-typed.
#[async_trait::async_trait]
pub trait EvidenceCollector {
    fn control_id(&self) -> &'static str;
    fn evidence_type(&self) -> &'static str;
    fn source(&self) -> &'static str;
    async fn collect(
        &self,
        db: &PgPool,
        period_start: DateTime<Utc>,
        period_end: DateTime<Utc>,
    ) -> Result<CollectedItem, String>;
}

pub struct AuditLogEvidenceCollector;

#[async_trait::async_trait]
impl EvidenceCollector for AuditLogEvidenceCollector {
    fn control_id(&self) -> &'static str {
        "CC2.1"
    }
    fn evidence_type(&self) -> &'static str {
        "audit_log_sample"
    }
    fn source(&self) -> &'static str {
        "audit_logs"
    }
    async fn collect(
        &self,
        db: &PgPool,
        period_start: DateTime<Utc>,
        period_end: DateTime<Utc>,
    ) -> Result<CollectedItem, String> {
        let (total,): (i64,) = sqlx::query_as(
            "SELECT COUNT(*) FROM audit_logs WHERE timestamp >= $1 AND timestamp < $2",
        )
        .bind(period_start)
        .bind(period_end)
        .fetch_one(db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;

        let by_action: Vec<(String, i64)> = sqlx::query_as(
            "SELECT action, COUNT(*) FROM audit_logs
             WHERE timestamp >= $1 AND timestamp < $2
             GROUP BY action ORDER BY COUNT(*) DESC LIMIT 25",
        )
        .bind(period_start)
        .bind(period_end)
        .fetch_all(db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;

        let by_outcome: Vec<(String, i64)> = sqlx::query_as(
            "SELECT outcome, COUNT(*) FROM audit_logs
             WHERE timestamp >= $1 AND timestamp < $2
             GROUP BY outcome",
        )
        .bind(period_start)
        .bind(period_end)
        .fetch_all(db)
        .await
        .map_err(|e| format!("DB error: {e}"))?;

        Ok(CollectedItem {
            payload: serde_json::json!({
                "total_entries": total,
                "by_action": by_action,
                "by_outcome": by_outcome,
            }),
            items: total as u64,
        })
    }
}

