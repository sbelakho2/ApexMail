/// Both frameworks' rows, in a stable order.
pub fn all_mappings() -> Vec<&'static ControlMapping> {
    DORA_MAPPINGS.iter().chain(NIS2_MAPPINGS.iter()).collect()
}

/// The served JSON: framework → rows, with counts, so a client can render the
/// evidence pack without knowing the order.
pub fn frameworks_view() -> serde_json::Value {
    let render = |rows: &[ControlMapping]| -> Vec<serde_json::Value> {
        rows.iter()
            .map(|row| {
                serde_json::json!({
                    "framework": row.framework,
                    "control_id": row.control_id,
                    "title": row.title,
                    "evidence": row.evidence,
                    "evidence_note": row.evidence_note,
                    "status": row.status,
                })
            })
            .collect()
    };
    serde_json::json!({
        "dora": render(DORA_MAPPINGS),
        "nis2": render(NIS2_MAPPINGS),
        "note": "Repository artifacts backing each control; every pointer is pinned by \
                 control_mappings::tests::every_mapped_evidence_pointer_exists. This is an \
                 evidence index, not a certification.",
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn repo_root() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../../..")
            .canonicalize()
            .expect("the crate must live inside the repository")
    }

    /// The truthfulness pin: every mapped evidence pointer EXISTS. A row whose
    /// artifact is deleted fails here, the mapping cannot outlive its
    /// evidence.
    #[test]
    fn every_mapped_evidence_pointer_exists() {
        let root = repo_root();
        for row in all_mappings() {
            assert!(
                root.join(row.evidence).exists(),
                "{} {} maps to `{}`, which does not exist in the repository",
                row.framework,
                row.control_id,
                row.evidence
            );
            assert!(
                !row.evidence_note.trim().is_empty(),
                "{} {} must say WHAT in the artifact backs the control",
                row.framework,
                row.control_id
            );
            assert!(
                matches!(row.status, "complete" | "partial" | "planned"),
                "{} {} has an unclassified status `{}`",
                row.framework,
                row.control_id,
                row.status
            );
        }
    }

    /// Control ids are unique per framework (a duplicated row would let one
    /// control's evidence silently substitute for another's).
    #[test]
    fn control_ids_are_unique_per_framework() {
        let mut seen: BTreeSet<(&str, &str)> = BTreeSet::new();
        for row in all_mappings() {
            assert!(
                seen.insert((row.framework, row.control_id)),
                "duplicate mapping row {} {}",
                row.framework,
                row.control_id
            );
        }
        assert!(
            DORA_MAPPINGS.len() >= 8,
            "DORA coverage must be substantive"
        );
        assert!(
            NIS2_MAPPINGS.len() >= 10,
            "NIS2 coverage must be substantive"
        );
    }

    /// The served view carries both frameworks with the same rows.
    #[test]
    fn frameworks_view_serves_both_frameworks() {
        let view = frameworks_view();
        assert_eq!(
            view["dora"].as_array().expect("dora array").len(),
            DORA_MAPPINGS.len()
        );
        assert_eq!(
            view["nis2"].as_array().expect("nis2 array").len(),
            NIS2_MAPPINGS.len()
        );
        assert!(view["note"]
            .as_str()
            .expect("note")
            .contains("not a certification"));
    }
}
