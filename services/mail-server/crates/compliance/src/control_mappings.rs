//! DORA / NIS2 control mapping, the "evidence pack" index.
//!
//! The plan's A-group promise is that every public claim is provable. Two EU
//! regimes make that promise concrete for an ICT service provider:
//!
//! * **DORA** (Regulation (EU) 2022/2554), the ICT third-party register
//!   (Art. 28), detection/logging (Art. 10), incident management and
//!   reporting (Art. 17/19) and the protection/continuity controls.
//! * **NIS2** (Directive (EU) 2022/2555), the Art. 21(2) basic risk
//!   management expectations and the Art. 23 reporting duty.
//!
//! # Truthfulness rule
//!
//! Every row below points at a REAL artifact in this repository (a source
//! file, a generated register, a CI gate) that can be opened and read. A row
//! whose evidence disappears FAILS the test suite
//! (`control_mappings::tests::every_mapped_evidence_pointer_exists`), and the
//! same rows are served publicly at `GET /v1/claims/frameworks` so an auditor
//! can follow the pointer without an NDA.
//!
//! What this module is NOT: a certification, an attestation of conformity, or
//! legal advice. It is the mapping an auditor would ask for FIRST ("which of
//! your systems do you claim covers Art. 28(3), and where is it?"), with
//! pointers that hold up. Rows we cannot back are deliberately ABSENT.

use serde::{Deserialize, Serialize};

/// One mapping row: a regulatory control and the repository artifact that
/// implements or evidences it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ControlMapping {
    /// The framework: `dora` or `nis2`.
    pub framework: &'static str,
    /// The control identifier as the regulation names it (e.g.
    /// `Art. 28(3)(a)`).
    pub control_id: &'static str,
    /// Human title of the control.
    pub title: &'static str,
    /// The repository path (relative to the repo root) that implements or
    /// evidences this control.
    pub evidence: &'static str,
    /// One sentence: WHAT in that artifact backs the control. Written so an
    /// auditor can verify the claim without reading the whole file.
    pub evidence_note: &'static str,
    /// Whether the current implementation is complete or has known gaps, and
    /// which, an honest mapping has no silent holes.
    pub status: &'static str,
}

