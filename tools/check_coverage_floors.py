#!/usr/bin/env python3
"""Required per-crate coverage floors (plan WP T2).

`ci/coverage-baseline.txt` holds ONE workspace line-coverage number. That
number hides per-crate regressions: a heavily-covered crate can mask a
service crate falling to zero. This gate replaces the single workspace
ratchet with per-crate LINE and REGION floors plus tier-1 diff coverage.

Semantics, in order:

  1. **Floors never drop.** Every crate in `ci/coverage-floors.toml` has a
     `line` floor and a `region` floor. A measured value below its floor
     fails. A crate with a floor but NO measurement in the report also fails
     (silence is not coverage).
  2. **Floors only rise.** The committed file is compared with the same file
     at `--base-ref` (default the previous commit). A floor may only be
     raised in the change that earned it; LOWERING one (or deleting a crate
     row) requires an active `[[waiver]]` for `test.coverage-floors` in
     `ci/waivers.toml` — a dated, owner-signed exception, never a silent
     edit. Waiver validity is enforced by tools/check_waivers.py.
  3. **Tier-1 diff coverage.** For every tier-1 crate (read from
     `ci/test-expectations.toml`), every changed line in the change set
     (`git diff --unified=0 <base-ref>`) that appears in the coverage
     instrumented data MUST be executed at least once. This is the honest
     approximation the plan permits: lcov carries per-LINE hits, not the
     compiler's region map, so a changed line that is not instrumented
     (comments, blank lines, non-code macros, unreachable `#[cfg]` items) is
     REPORTED but not failed by line; a changed source FILE with no
     instrumentation data at all (nothing in it was reachable by the test
     run) FAILS. The report always says which lines were skipped and why.

Inputs:
  * lcov (`llvm-cov` `--lcov`): `SF:`/`DA:` records → line coverage and
    per-file line hits. Generated by the test stage at
    `$RUN_DIR/coverage.lcov`.
  * cargo-llvm-cov JSON (`--json`): llvm-cov export format → region
    coverage. The test stage writes `$RUN_DIR/coverage.json` from the SAME
    instrumented run WHEN the installed cargo-llvm-cov supports
    `--output-dir` with both formats; without it region floors are reported
    as UNMEASURED and any crate with a non-zero region floor fails with the
    command to run.

Seeding:
  * The file ships with every workspace crate at `line = 0.0` /
    `region = 0.0` (the same convention as the workspace baseline, which
    shipped at 0.0 and was seeded by the first host measurement). A zero
    floor enforces nothing and is reported as UNSEEDED.
  * `--seed` raises each floor to the measured value (truncated to two
    decimals). It NEVER lowers a floor and never deletes a crate: the
    committed file is a ratchet even when regenerated.

Usage:
  check_coverage_floors.py --report RUN_DIR/coverage.lcov \\
      [--json RUN_DIR/coverage.json] [--base-ref REF] [--no-diff]
  check_coverage_floors.py --report ... --json ... --seed
  check_coverage_floors.py --self-test

Exit codes: 0 = clean, 1 = violation, 2 = usage/IO error.
"""

from __future__ import annotations

import datetime as dt
import json
import math
import re
import subprocess
import sys
import tempfile
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WS = REPO / "services" / "mail-server" / "crates"
FLOORS = REPO / "ci" / "coverage-floors.toml"
WAIVERS = REPO / "ci" / "waivers.toml"
EXPECTATIONS = REPO / "ci" / "test-expectations.toml"
FLOOR_LANE = "test.coverage-floors"

# Files that are never expected to carry executable coverage. Diff coverage
# ignores them (documented approximation).
NON_INSTRUMENTED_SUFFIXES = (".md", ".toml", ".json", ".yaml", ".yml", ".sql", ".sh")


@dataclass
class CrateCoverage:
    line_total: int = 0
    line_hit: int = 0
    region_total: int = 0
    region_hit: int = 0
    regions_measured: bool = False
    files: dict[str, dict[int, int]] = field(default_factory=dict)  # file → line → hits
    instrumented_files: set[str] = field(default_factory=set)

    @property
    def line_pct(self) -> float:
        return round(100.0 * self.line_hit / self.line_total, 4) if self.line_total else 0.0

    @property
    def region_pct(self) -> float:
        if not self.regions_measured or not self.region_total:
            return 0.0
        return round(100.0 * self.region_hit / self.region_total, 4)


def crate_for_path(path: str) -> str | None:
    """Map an instrumented source path to its workspace crate."""
    normalized = path.replace("\\", "/")
    marker = "/services/mail-server/crates/"
    if marker in normalized:
        rest = normalized.split(marker, 1)[1]
        return rest.split("/", 1)[0]
    # Relative lcov paths (nextest run from the workspace root).
    match = re.search(r"(?:^|/)crates/([^/]+)/", normalized)
    if match:
        return match.group(1)
    return None


def parse_lcov(text: str) -> dict[str, CrateCoverage]:
    crates: dict[str, CrateCoverage] = {}
    current_file: str | None = None
    for raw in text.splitlines():
        if raw.startswith("SF:"):
            current_file = raw[3:].strip()
        elif raw.startswith("DA:") and current_file:
            crate = crate_for_path(current_file)
            if not crate:
                continue
            payload = raw[3:].split(",", 1)
            try:
                line_no, hits = int(payload[0]), int(payload[1])
            except (ValueError, IndexError):
                continue
            entry = crates.setdefault(crate, CrateCoverage())
            entry.line_total += 1
            if hits > 0:
                entry.line_hit += 1
            entry.files.setdefault(current_file, {})[line_no] = hits
            entry.instrumented_files.add(current_file)
        elif raw.strip() == "end_of_record":
            current_file = None
    return crates


def parse_llvm_cov_json(text: str) -> dict[str, CrateCoverage]:
    """Parse `llvm-cov export` JSON (cargo-llvm-cov --json)."""
    document = json.loads(text)
    crates: dict[str, CrateCoverage] = {}
    for data in document.get("data", []):
        for file_entry in data.get("files", []):
            filename = file_entry.get("filename", "")
            crate = crate_for_path(filename)
            if not crate:
                continue
            summary = file_entry.get("summary", {})
            regions = summary.get("regions", {})
            lines = summary.get("lines", {})
            entry = crates.setdefault(crate, CrateCoverage())
            entry.regions_measured = True
            entry.region_total += int(regions.get("count", 0))
            entry.region_hit += int(regions.get("covered", 0))
            # Keep line data from the JSON too (it is the same source as
            # lcov when both are produced by one run; lcov wins if present).
            if not entry.line_total:
                entry.line_total += int(lines.get("count", 0))
                entry.line_hit += int(lines.get("covered", 0))
            entry.instrumented_files.add(filename)
    return crates


def merge(lcov: dict[str, CrateCoverage], json_cov: dict[str, CrateCoverage]) -> dict[str, CrateCoverage]:
    merged = dict(lcov)
    for crate, entry in json_cov.items():
        target = merged.setdefault(crate, CrateCoverage())
        target.region_total = entry.region_total
        target.region_hit = entry.region_hit
        target.regions_measured = entry.regions_measured
        target.instrumented_files |= entry.instrumented_files
        if not target.line_total:
            target.line_total = entry.line_total
            target.line_hit = entry.line_hit
    return merged


def workspace_crates() -> list[str]:
    return sorted(path.name for path in WS.iterdir() if path.is_dir())


def load_floors(path: Path) -> dict[str, dict[str, float]]:
    data = tomllib.loads(path.read_text())
    floors = data.get("floor", {})
    result: dict[str, dict[str, float]] = {}
    for crate, entry in floors.items():
        result[crate] = {
            "line": float(entry.get("line", 0.0)),
            "region": float(entry.get("region", 0.0)),
        }
    return result


def tier1_crates(path: Path) -> set[str]:
    data = tomllib.loads(path.read_text())
    return {
        name
        for name, entry in data.get("package", {}).items()
        if entry.get("tier") == 1
    }


def active_waiver(waivers_path: Path, lane: str, today: dt.date | None = None) -> bool:
    if not waivers_path.exists():
        return False
    today = today or dt.date.today()
    data = tomllib.loads(waivers_path.read_text())
    for waiver in data.get("waiver", []):
        if str(waiver.get("lane", "")).strip() != lane:
            continue
        try:
            expires = dt.date.fromisoformat(str(waiver["expires"]))
        except (KeyError, ValueError):
            continue
        if expires >= today:
            return True
    return False


def load_previous_floors(base_ref: str) -> dict[str, dict[str, float]] | None:
    try:
        shown = subprocess.run(
            ["git", "-C", str(REPO), "show", f"{base_ref}:ci/coverage-floors.toml"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    try:
        data = tomllib.loads(shown.stdout)
    except tomllib.TOMLDecodeError:
        return None
    result: dict[str, dict[str, float]] = {}
    for crate, entry in data.get("floor", {}).items():
        result[crate] = {
            "line": float(entry.get("line", 0.0)),
            "region": float(entry.get("region", 0.0)),
        }
    return result


def ratchet_problems(
    floors: dict[str, dict[str, float]],
    previous: dict[str, dict[str, float]] | None,
    *,
    waived: bool,
) -> list[str]:
    if previous is None or waived:
        return []
    problems: list[str] = []
    for crate, old in previous.items():
        new = floors.get(crate)
        if new is None:
            problems.append(
                f"{crate}: floor row deleted (lowering a floor requires a "
                f"{FLOOR_LANE} waiver)"
            )
            continue
        for metric in ("line", "region"):
            if new.get(metric, 0.0) < old.get(metric, 0.0) - 1e-9:
                problems.append(
                    f"{crate}: {metric} floor lowered {old.get(metric, 0.0):.2f} -> "
                    f"{new.get(metric, 0.0):.2f} (raise-only; a {FLOOR_LANE} waiver "
                    "is required to lower one)"
                )
    return problems


@dataclass
class DiffResult:
    checked_lines: int = 0
    uncovered: list[str] = field(default_factory=list)
    uninstrumented_files: list[str] = field(default_factory=list)
    skipped_lines: int = 0


def changed_lines(base_ref: str, crate: str) -> dict[str, set[int]]:
    """Added line numbers per changed file for one crate (git diff -U0)."""
    path = f"services/mail-server/crates/{crate}"
    try:
        diff = subprocess.run(
            ["git", "-C", str(REPO), "diff", "--unified=0", base_ref, "--", path],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError) as error:
        raise RuntimeError(f"git diff {base_ref} -- {path} failed: {error}") from error
    result: dict[str, set[int]] = {}
    current: str | None = None
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            current = line[6:]
            result.setdefault(current, set())
        elif line.startswith("@@") and current:
            match = re.search(r"\+(\d+)(?:,(\d+))?", line)
            if not match:
                continue
            start = int(match.group(1))
            count = int(match.group(2) or "1")
            result[current].update(range(start, start + count))
    return {path: lines for path, lines in result.items() if lines}


def diff_coverage_problems(
    coverage: dict[str, CrateCoverage],
    tiers: set[str],
    base_ref: str,
) -> tuple[list[str], DiffResult]:
    problems: list[str] = []
    result = DiffResult()
    for crate in sorted(tiers & set(workspace_crates())):
        try:
            changed = changed_lines(base_ref, crate)
        except RuntimeError as error:
            problems.append(str(error))
            continue
        covered = coverage.get(crate)
        for path, lines in changed.items():
            if path.endswith(NON_INSTRUMENTED_SUFFIXES) or "/tests/" in path:
                result.skipped_lines += len(lines)
                continue
            file_hits = covered.files.get(path) if covered else None
            if not file_hits:
                result.uninstrumented_files.append(path)
                problems.append(
                    f"{crate}: changed file {path} has NO coverage instrumentation "
                    "(nothing in it was reached by the instrumented test run)"
                )
                continue
            for line_no in sorted(lines):
                hits = file_hits.get(line_no)
                if hits is None:
                    result.skipped_lines += 1
                    continue
                result.checked_lines += 1
                if hits <= 0:
                    result.uncovered.append(f"{path}:{line_no}")
    return problems, result


def seed_text(floors: dict[str, dict[str, float]], crates: list[str]) -> str:
    measured = sorted(floors)
    lines = [
        "# ci/coverage-floors.toml — REQUIRED per-crate coverage floors (T2).",
        "#",
        "# GENERATED by `tools/check_coverage_floors.py --seed` from the",
        "# instrumented run the test stage records ($RUN_DIR/coverage.lcov +",
        "# coverage.json). Do not hand-edit numbers to LOWER a floor: lowering",
        "# requires a dated `test.coverage-floors` waiver in ci/waivers.toml.",
        "# Raising a floor in the change that earned it is the expected action.",
        "#",
        "# line   — lcov DA hit/total over the crate's instrumented lines.",
        "# region — llvm-cov export region coverage (cargo-llvm-cov --json).",
        "#",
        "# A 0.0 floor is UNSEEDED: the crate has not produced a per-crate",
        "# measurement yet (the file ships at 0.0 by the same convention as the",
        "# workspace baseline, which also shipped at 0.0 until the first host",
        "# run). The first CI run with BOTH artifacts MUST run:",
        "#   python3 tools/check_coverage_floors.py --report <lcov> \\",
        "#       --json <llvm-cov-json> --seed",
        "# and commit the raised values in the same change. --seed is raise-only:",
        "# it can never lower a floor, even when regenerating the file.",
        "",
        "[workspace]",
        "# The workspace-wide ratchet remains authoritative for the number in",
        "# ci/coverage-baseline.txt; this table records how the run was measured.",
        f'measured = "{dt.date.today().isoformat()}"',
        "# NOTE: this commit ships every crate at 0.00. A full workspace",
        "# instrumented run was deliberately not performed in this change (the",
        "# plan's gate budget forbids a full workspace test run), so there is no",
        "# honest per-crate measurement to seed; the first CI run seeds it.",
        "",
    ]
    for crate in sorted(set(crates) | set(measured)):
        floor = floors.get(crate, {"line": 0.0, "region": 0.0})
        lines.append(f'[floor."{crate}"]')
        lines.append(f"line = {floor['line']:.2f}")
        lines.append(f"region = {floor['region']:.2f}")
        lines.append("")
    return "\n".join(lines)


def raise_floors(
    floors: dict[str, dict[str, float]],
    coverage: dict[str, CrateCoverage],
    crates: list[str],
) -> dict[str, dict[str, float]]:
    updated: dict[str, dict[str, float]] = {}
    for crate in sorted(set(crates) | set(floors)):
        current = floors.get(crate, {"line": 0.0, "region": 0.0})
        measured = coverage.get(crate)
        line = current["line"]
        region = current["region"]
        # Truncate DOWN so the committed floor is always at or below the
        # measured value (rounding up would make the next run fail by a
        # fraction of a percent).
        if measured and measured.line_total:
            line = max(line, math.floor(measured.line_pct * 100.0) / 100.0)
        if measured and measured.regions_measured and measured.region_total:
            region = max(region, math.floor(measured.region_pct * 100.0) / 100.0)
        updated[crate] = {"line": line, "region": region}
    return updated


def check(
    coverage: dict[str, CrateCoverage],
    floors: dict[str, dict[str, float]],
    *,
    regions_required: bool,
    unseeded_warn: list[str] | None = None,
) -> list[str]:
    problems: list[str] = []
    for crate, floor in sorted(floors.items()):
        measured = coverage.get(crate)
        if measured is None or (not measured.line_total and not measured.region_total):
            # An UNSEEDED crate (0.0 floor) may legitimately produce no DA
            # records (a code-less test crate); there is nothing to enforce.
            # A crate with a real floor must be measured: silence is not
            # coverage.
            if floor["line"] == 0 and floor["region"] == 0:
                continue
            problems.append(
                f"{crate}: floored crate has NO measurement in the report "
                "(a crate that disappears from coverage silently skips its floor)"
            )
            continue
        if floor["line"] > 0 and measured.line_pct + 1e-9 < floor["line"]:
            problems.append(
                f"{crate}: line {measured.line_pct:.2f}% < floor {floor['line']:.2f}%"
            )
        if floor["region"] > 0:
            if not regions_required and not measured.regions_measured:
                continue
            if not measured.regions_measured:
                problems.append(
                    f"{crate}: region floor {floor['region']:.2f}% is set but no "
                    "llvm-cov JSON report was supplied (run cargo llvm-cov with --json)"
                )
            elif measured.region_pct + 1e-9 < floor["region"]:
                problems.append(
                    f"{crate}: region {measured.region_pct:.2f}% < floor "
                    f"{floor['region']:.2f}%"
                )
        if unseeded_warn is not None and floor["line"] == 0 and floor["region"] == 0:
            unseeded_warn.append(crate)
    return problems


def report(
    coverage: dict[str, CrateCoverage],
    floors: dict[str, dict[str, float]],
    diff: DiffResult,
) -> None:
    print(f"{'crate':32} {'line%':>8} {'floor':>8} {'region%':>8} {'floor':>8}  status")
    for crate, floor in sorted(floors.items()):
        measured = coverage.get(crate)
        if measured is None or not measured.line_total:
            print(f"{crate:32} {'--':>8} {floor['line']:>8.2f} {'--':>8} {floor['region']:>8.2f}  UNMEASURED")
            continue
        line_ok = measured.line_pct + 1e-9 >= floor["line"] if floor["line"] > 0 else True
        region_ok = (
            measured.region_pct + 1e-9 >= floor["region"]
            if floor["region"] > 0 and measured.regions_measured
            else True
        )
        status = "PASS" if line_ok and region_ok else "FAIL"
        if floor["line"] == 0 and floor["region"] == 0:
            status = "UNSEEDED"
        region_text = f"{measured.region_pct:8.2f}" if measured.regions_measured else "    --  "
        print(
            f"{crate:32} {measured.line_pct:8.2f} {floor['line']:8.2f} "
            f"{region_text} {floor['region']:8.2f}  {status}"
        )
    print()
    print(
        f"tier-1 diff coverage: {diff.checked_lines} changed instrumented line(s) "
        f"checked, {len(diff.uncovered)} uncovered, {diff.skipped_lines} "
        f"non-instrumented line(s) skipped, {len(diff.uninstrumented_files)} "
        "changed file(s) with no instrumentation"
    )
    if diff.skipped_lines or diff.uninstrumented_files:
        print(
            "NOTE (honest approximation): lcov carries per-LINE execution "
            "counts, not region maps. Added lines with no DA record are "
            "reported as skipped (comments, macro-only lines, cfg'd-out "
            "code); they are not silently counted as covered."
        )


def run_self_test() -> int:
    lcov_ok = """SF:/repo/services/mail-server/crates/alpha/src/lib.rs
DA:1,1
DA:2,1
DA:3,0
end_of_record
SF:/repo/services/mail-server/crates/beta/src/lib.rs
DA:1,0
DA:2,0
end_of_record
"""
    coverage = parse_lcov(lcov_ok)
    if coverage["alpha"].line_pct != round(200.0 / 3.0, 4):
        print("self-test FAIL: lcov line aggregation", file=sys.stderr)
        return 1
    if coverage["beta"].line_pct != 0.0:
        print("self-test FAIL: zero-hit crate", file=sys.stderr)
        return 1

    # 1. A drop below the floor fails.
    floors = {"alpha": {"line": 70.0, "region": 0.0}, "beta": {"line": 0.0, "region": 0.0}}
    problems = check(coverage, floors, regions_required=False)
    if not any("alpha: line" in p for p in problems):
        print("self-test FAIL: a line drop was not caught", file=sys.stderr)
        return 1

    # 2. A rise (or meeting the floor) passes.
    floors = {"alpha": {"line": 60.0, "region": 0.0}}
    if check(coverage, floors, regions_required=False):
        print("self-test FAIL: meeting the floor was rejected", file=sys.stderr)
        return 1

    # 3. A floored crate with no measurement fails.
    problems = check(coverage, {"ghost": {"line": 50.0, "region": 0.0}}, regions_required=False)
    if not any("NO measurement" in p for p in problems):
        print("self-test FAIL: an unmeasured floored crate was accepted", file=sys.stderr)
        return 1

    # 4. Ratchet: lowering fails; an active waiver covers it.
    previous = {"alpha": {"line": 80.0, "region": 10.0}}
    lowered = {"alpha": {"line": 70.0, "region": 10.0}}
    problems = ratchet_problems(lowered, previous, waived=False)
    if len(problems) != 1 or "lowered" not in problems[0]:
        print("self-test FAIL: a lowered floor was accepted", file=sys.stderr)
        return 1
    if ratchet_problems(lowered, previous, waived=True):
        print("self-test FAIL: a waiver did not cover the lowering", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        waiver = Path(tmp) / "waivers.toml"
        waiver.write_text(
            "[[waiver]]\n"
            f'lane = "{FLOOR_LANE}"\n'
            'reason = "measured drop while a service is split"\n'
            'owner = "owner"\n'
            'written = "2026-10-01"\n'
            'expires = "2099-01-01"\n'
        )
        if not active_waiver(waiver, FLOOR_LANE):
            print("self-test FAIL: an unexpired floor waiver was ignored", file=sys.stderr)
            return 1
        waiver.write_text(
            "[[waiver]]\n"
            f'lane = "{FLOOR_LANE}"\n'
            'reason = "expired"\n'
            'owner = "owner"\n'
            'written = "2020-01-01"\n'
            'expires = "2020-01-02"\n'
        )
        if active_waiver(waiver, FLOOR_LANE):
            print("self-test FAIL: an expired floor waiver still covered", file=sys.stderr)
            return 1

    # 5. Seed raises but never lowers.
    seeded = raise_floors(
        {"alpha": {"line": 10.0, "region": 0.0}, "beta": {"line": 0.0, "region": 0.0}},
        coverage,
        ["alpha", "beta"],
    )
    if seeded["alpha"]["line"] != 66.66:
        print(f"self-test FAIL: seed did not raise alpha ({seeded['alpha']['line']})", file=sys.stderr)
        return 1
    if seeded["beta"]["line"] != 0.0:
        print("self-test FAIL: seed invented coverage for beta", file=sys.stderr)
        return 1
    lowered_seed = raise_floors({"alpha": {"line": 99.0, "region": 0.0}}, coverage, ["alpha"])
    if lowered_seed["alpha"]["line"] != 99.0:
        print("self-test FAIL: seed LOWERED an existing floor", file=sys.stderr)
        return 1

    # 6. JSON region parsing + region floor failure.
    payload = {
        "data": [
            {
                "files": [
                    {
                        "filename": "/repo/services/mail-server/crates/alpha/src/lib.rs",
                        "summary": {"regions": {"count": 10, "covered": 8}},
                    }
                ]
            }
        ]
    }
    json_cov = parse_llvm_cov_json(json.dumps(payload))
    if json_cov["alpha"].region_pct != 80.0:
        print("self-test FAIL: JSON region aggregation", file=sys.stderr)
        return 1
    problems = check(
        merge(coverage, json_cov),
        {"alpha": {"line": 60.0, "region": 90.0}},
        regions_required=True,
    )
    if not any("region" in p for p in problems):
        print("self-test FAIL: a region drop was not caught", file=sys.stderr)
        return 1

    # 7. Diff coverage: covered added line passes; uncovered fails; a changed
    #    file with no instrumentation fails.
    coverage["alpha"].files["/repo/services/mail-server/crates/alpha/src/lib.rs"] = {
        1: 1,
        2: 0,
    }
    diff_problems, diff = diff_coverage_problems_with(
        coverage, {"alpha"}, {"/repo/services/mail-server/crates/alpha/src/lib.rs": {1}}
    )
    if diff_problems or diff.checked_lines != 1 or diff.uncovered:
        print("self-test FAIL: a covered changed line failed", file=sys.stderr)
        return 1
    diff_problems, diff = diff_coverage_problems_with(
        coverage, {"alpha"}, {"/repo/services/mail-server/crates/alpha/src/lib.rs": {2}}
    )
    if not diff.uncovered or not diff_problems:
        print("self-test FAIL: an uncovered changed line passed", file=sys.stderr)
        return 1
    diff_problems, diff = diff_coverage_problems_with(
        coverage,
        {"alpha"},
        {"/repo/services/mail-server/crates/alpha/src/brand_new.rs": {1}},
    )
    if not any("NO coverage instrumentation" in p for p in diff_problems):
        print("self-test FAIL: an uninstrumented changed file passed", file=sys.stderr)
        return 1

    # 8. Seed text round-trips as TOML and keeps every crate.
    text = seed_text(seeded, ["alpha", "beta", "gamma"])
    parsed = tomllib.loads(text)["floor"]
    if set(parsed) != {"alpha", "beta", "gamma"}:
        print("self-test FAIL: seeded file lost a crate", file=sys.stderr)
        return 1

    print(
        "self-test: ok (drop fails, floor met passes, unmeasured floored crate "
        "fails, lowered floor needs an active waiver, seed raises only, region "
        "drop fails, diff coverage catches uncovered/instrumented-less changed "
        "files)"
    )
    return 0


def diff_coverage_problems_with(
    coverage: dict[str, CrateCoverage],
    tiers: set[str],
    changed: dict[str, set[int]],
) -> tuple[list[str], DiffResult]:
    """The diff-coverage core with an INJECTED change set (self-test)."""
    problems: list[str] = []
    result = DiffResult()
    for crate in sorted(tiers):
        covered = coverage.get(crate)
        for path, lines in changed.items():
            if path.endswith(NON_INSTRUMENTED_SUFFIXES) or "/tests/" in path:
                result.skipped_lines += len(lines)
                continue
            file_hits = covered.files.get(path) if covered else None
            if not file_hits:
                result.uninstrumented_files.append(path)
                problems.append(
                    f"{crate}: changed file {path} has NO coverage instrumentation "
                    "(nothing in it was reached by the instrumented test run)"
                )
                continue
            for line_no in sorted(lines):
                hits = file_hits.get(line_no)
                if hits is None:
                    result.skipped_lines += 1
                    continue
                result.checked_lines += 1
                if hits <= 0:
                    result.uncovered.append(f"{path}:{line_no}")
    if result.uncovered:
        problems.append(
            "tier-1 diff coverage: changed line(s) not executed by tests: "
            + ", ".join(result.uncovered[:20])
        )
    return problems, result


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return run_self_test()

    def value(flag: str, default: str | None = None) -> str | None:
        if flag in argv:
            index = argv.index(flag)
            try:
                return argv[index + 1]
            except IndexError:
                raise SystemExit(f"{flag} needs a value")
        return default

    report_path = value("--report")
    if not report_path:
        print("usage: check_coverage_floors.py --report RUN_DIR/coverage.lcov "
              "[--json RUN_DIR/coverage.json] [--base-ref REF] [--no-diff] [--seed]",
              file=sys.stderr)
        return 2
    lcov_path = Path(report_path)
    if not lcov_path.is_file():
        print(f"coverage report missing: {lcov_path}", file=sys.stderr)
        return 2
    json_path = value("--json")
    floors_path = Path(value("--floors", str(FLOORS)) or str(FLOORS))
    waivers_path = Path(value("--waivers", str(WAIVERS)) or str(WAIVERS))
    expectations = Path(value("--expectations", str(EXPECTATIONS)) or str(EXPECTATIONS))
    base_ref = value("--base-ref", "HEAD~1") or "HEAD~1"
    seed = "--seed" in argv
    no_diff = "--no-diff" in argv

    coverage = parse_lcov(lcov_path.read_text(errors="replace"))
    if json_path:
        path = Path(json_path)
        if path.is_file():
            try:
                coverage = merge(coverage, parse_llvm_cov_json(path.read_text(errors="replace")))
            except (json.JSONDecodeError, KeyError, TypeError) as error:
                print(f"coverage JSON unreadable: {error}", file=sys.stderr)
                return 2

    if seed:
        floors = load_floors(floors_path) if floors_path.is_file() else {}
        updated = raise_floors(floors, coverage, workspace_crates())
        floors_path.write_text(seed_text(updated, workspace_crates()))
        print(f"seeded {len(updated)} crate floors from {lcov_path} "
              f"(raise-only; committed values never drop)")
        return 0

    if not floors_path.is_file():
        print(f"coverage floors file missing: {floors_path}", file=sys.stderr)
        return 2
    floors = load_floors(floors_path)
    unseeded: list[str] = []
    problems = check(coverage, floors, regions_required=True, unseeded_warn=unseeded)

    previous = load_previous_floors(base_ref)
    waived = active_waiver(waivers_path, FLOOR_LANE)
    problems.extend(ratchet_problems(floors, previous, waived=waived))
    if previous is None:
        print(
            f"WARNING: could not read ci/coverage-floors.toml at {base_ref}; "
            "the raise-only check was skipped for this run",
            file=sys.stderr,
        )

    diff = DiffResult()
    if not no_diff:
        tiers = tier1_crates(expectations)
        diff_problems, diff = diff_coverage_problems(coverage, tiers, base_ref)
        problems.extend(diff_problems)

    report(coverage, floors, diff)
    if unseeded:
        print(
            f"UNSEEDED: {len(unseeded)} crate(s) still carry a 0.0 floor "
            f"(no per-crate measurement yet). Run with --seed on the CI machine: "
            f"{', '.join(unseeded[:12])}{' …' if len(unseeded) > 12 else ''}"
        )
    if problems:
        print(f"COVERAGE FLOORS FAILED — {len(problems)} problem(s):", file=sys.stderr)
        for problem in problems[:60]:
            print(f"  - {problem}", file=sys.stderr)
        if len(problems) > 60:
            print(f"  … and {len(problems) - 60} more", file=sys.stderr)
        return 1
    print(
        f"coverage floors: {len(floors)} crate(s) at or above floor; "
        "tier-1 diff coverage clean"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
