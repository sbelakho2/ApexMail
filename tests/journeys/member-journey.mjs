import { chromium } from "playwright";
const BASE = "http://127.0.0.1:8080";
const OUT = "/Users/sabelakhoua/IdeaProjects/ApexMail/.kiwi/journey-shots";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto(BASE + "/login");
await page.getByLabel(/email/i).fill("member@journey.test");
await page.getByLabel(/password/i).fill("Journey!2026-Strong-Pass-3");
await page.waitForTimeout(1200);
await page.locator("button[type=submit]").click();
await page.waitForLoadState("domcontentloaded");
await page.waitForTimeout(600);
console.log("member login:", page.url());
await page.screenshot({ path: `${OUT}/member-dashboard.png` });
await page.goto(BASE + "/settings/team");
await page.waitForLoadState("domcontentloaded");
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/member-settings-team.png` });
const snap = await page.locator("main").ariaSnapshot();
console.log("team page restricted copy:", /owner|admin|restricted|cannot/i.test(snap) ? "yes" : "check");
await page.goto(BASE + "/settings/billing");
await page.waitForLoadState("domcontentloaded");
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/member-settings-billing.png` });
console.log("billing url:", page.url());
await browser.close();
