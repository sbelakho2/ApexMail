import { chromium } from "playwright";
const BASE = "http://127.0.0.1:8080";
const OUT = "/Users/sabelakhoua/IdeaProjects/ApexMail/.kiwi/journey-shots";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto(BASE + "/login");
await page.getByLabel(/email/i).fill("owner@journey.test");
await page.getByLabel(/password/i).fill("Journey!2026-Strong-Pass-1");
await page.waitForTimeout(1200);
await page.locator("button[type=submit]").click();
await page.waitForURL("**/dashboard", { timeout: 15000 });
await page.goto(BASE + "/contacts/new");
await page.getByRole("textbox", { name: /email/i }).first().fill("ada@journey.test");
await page.getByRole("textbox", { name: /name/i }).first().fill("Ada Lovelace");
await page.getByRole("button", { name: "Add Contact" }).click();
await page.waitForLoadState("domcontentloaded");
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/owner-contact-created.png` });
console.log("url:", page.url());
const snap = await page.locator("main").ariaSnapshot();
console.log(snap.slice(0, 700));
// now verify it appears in the list
await page.goto(BASE + "/contacts");
await page.waitForLoadState("domcontentloaded");
const listSnap = await page.locator("main").ariaSnapshot();
console.log("---LIST---");
console.log(listSnap.includes("ada@journey.test") ? "CONTACT LISTED" : "CONTACT MISSING");
await page.screenshot({ path: `${OUT}/owner-contacts-list.png` });
await browser.close();
